/** Lowercase, strip accents and punctuation so "côte d'ivoire" matches "Cote dIvoire". */
export function normalise(s: string): string {
  return s
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    // Apostrophes vanish (d'Ivoire -> divoire); hyphens, dots and slashes become spaces (Guinea-Bissau).
    .replace(/['’`]/g, '')
    .replace(/[^a-z0-9 ]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}
